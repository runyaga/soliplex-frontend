/// A module's complete bindings plus the schema types used by its stubs.
class ModuleBindings {
  ModuleBindings(this.name);

  final String name;
  final types = SchemaTypes(definitions: hostValueDefinitions);
  final functions = <FunctionBinding>[];

  String get stubs {
    final opaque = [
      for (final value in hostValueDefinitions.values)
        if (SchemaTypes.map(SchemaTypes.map(value)['x-python'])['opaque']
            case final String handle)
          handle,
    ];
    final body = [
      if (name == 'ui') ...opaque.map((handle) => 'class $handle: ...'),
      ...types.declarations.values,
      ...functions.map((f) => f.stub),
    ].join('\n');
    bool uses(String symbol) => RegExp('\\b$symbol\\b').hasMatch(body);
    final typing = [
      'Any',
      'Literal',
      'Never',
      'NotRequired',
      'TypedDict',
      'overload',
    ].where(uses).join(', ');
    final handles = opaque.where(uses).join(', ');
    return [
      '# Generated by tool/generate_bindings.dart. Do not edit.',
      if (typing.isNotEmpty) 'from typing import $typing',
      if (name == 'ui' || handles.isNotEmpty) '',
      if (name == 'ui') ...[
        'from . import graphics as graphics',
        'from . import workbench as workbench',
      ] else if (handles.isNotEmpty)
        'from ui import $handles',
      '',
      body,
    ].join('\n');
  }
}

/// Fresh generation is intentional: drift tests compare it to committed text.
Map<String, ModuleBindings> generateBindings() => {
  for (final entry in hostFunctionSchemas().entries)
    entry.key: _module(entry.key, entry.value),
};

ModuleBindings _module(String name, List<Map<String, Object?>> schemas) {
  final module = ModuleBindings(name);
  for (final schema in schemas) {
    module.functions.add(FunctionBinding.fromSchema(schema, module.types));
  }
  return module;
}

final Map<String, ModuleBindings> moduleBindings = generateBindings();
final List<FunctionBinding> uiFunctions = moduleBindings['ui']!.functions
    .where(
      (binding) =>
          uiHostFunctionSchemas.any((schema) => schema['name'] == binding.name),
    )
    .toList();
final List<FunctionBinding> workbenchBindings =
    moduleBindings['ui.workbench']!.functions;
