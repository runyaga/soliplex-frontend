/// A module's complete bindings plus the schema types used by its stubs.
class ModuleBindings {
  ModuleBindings(this.name);

  final String name;
  final types = SchemaTypes();
  final functions = <FunctionBinding>[];

  String get stubs {
    final body = [
      if (name == 'ui') ...['class Binding: ...', 'class EventHandle: ...'],
      ...types.declarations.values,
      ...functions.map((f) => f.stub),
    ].join('\n');
    bool uses(String symbol) => RegExp('\\b$symbol\\b').hasMatch(body);
    final typing = [
      'Any',
      'Literal',
      'Never',
      'NotRequired',
      'TypedDict',
      'overload',
    ].where(uses).join(', ');
    final handles = ['Binding', 'EventHandle'].where(uses).join(', ');
    return [
      '# Generated by tool/generate_bindings.dart. Do not edit.',
      if (typing.isNotEmpty) 'from typing import $typing',
      if (name == 'ui' || handles.isNotEmpty) '',
      if (name == 'ui') ...[
        'from . import graphics as graphics',
        'from . import workbench as workbench',
      ] else if (handles.isNotEmpty)
        'from ui import $handles',
      '',
      body,
    ].join('\n');
  }

  /// Generates constructor parameters from a registered catalog schema.
  void constructor(
    String name,
    Map<String, Object?> schema,
    List<String> order, {
    Map<String, PythonType> adapters = const {},
  }) {
    final flat = SchemaTypes.flatten(schema);
    final props = SchemaTypes.map(flat['properties'])..remove('component');
    final required = (flat['required']! as List).cast<String>();
    final names = [
      ...order,
      ...props.keys.where(
        (key) =>
            !order.contains(key) && RegExp(r'^[a-zA-Z_]\w*$').hasMatch(key),
      ),
      'id',
    ];
    functions.add(
      FunctionBinding(
        name,
        [
          for (final key in names)
            BindingParameter(
              key,
              key == 'id'
                  ? pyString
                  : adapters[key] ??
                        types.type(
                          SchemaTypes.map(props[key]),
                          '$name${SchemaTypes.identifier(key)}',
                        ),
              keywordOnly: !order.contains(key),
              defaultValue: required.contains(key)
                  ? null
                  : SchemaTypes.map(props[key]).containsKey('default')
                  ? pythonValue(SchemaTypes.map(props[key])['default'])
                  : '...',
              defaultDart: SchemaTypes.map(props[key])['default'],
            ),
        ],
        pyString,
        'Construct a $name component handle.',
      ),
    );
  }
}

/// Fresh generation is intentional: drift tests compare it to committed text.
Map<String, ModuleBindings> generateBindings() {
  final ui = ModuleBindings('ui')..functions.addAll(uiFunctions);
  final graphics = ModuleBindings('ui.graphics');
  final chart = ModuleBindings('chart');
  final workbench = ModuleBindings('ui.workbench')
    ..functions.addAll(workbenchBindings);

  final basic = basicCatalog();
  for (final MapEntry(:key, :value) in basicSignatures.entries) {
    ui.constructor(
      key,
      basic.components[key]!.schema.value,
      value,
      adapters: {
        // The Python convenience layer accepts bare option strings too.
        if (key == 'ChoicePicker')
          'options':
              (ui.types.type(
                SchemaTypes.map(
                  SchemaTypes.map(
                    SchemaTypes.flatten(
                      basic.components[key]!.schema.value,
                    )['properties'],
                  )['options'],
                ),
                'ChoicePickerOptions',
              ) |
              pyString.list),
      },
    );
  }
  final chartSchema = chartGraphicsCatalog().components['Chart']!.schema.value;
  final chartProps = SchemaTypes.map(chartSchema['properties']);
  final kinds = (SchemaTypes.map(chartProps['spec'])['oneOf']! as List)
      .map(SchemaTypes.map)
      .toList();
  for (final schema in kinds) {
    final props = SchemaTypes.map(schema['properties']);
    final kind = SchemaTypes.map(props['kind'])['const']! as String;
    final required = (schema['required']! as List).cast<String>();
    final data = switch (kind) {
      'bar' => ['points'],
      'gauge' => ['value'],
      'pie' => ['slices'],
      'radar' => ['axes', 'series'],
      'candlestick' => ['candles'],
      _ => ['series'],
    };
    chart.functions.add(
      FunctionBinding(
        kind,
        [
          for (final key in [
            ...data,
            ...props.keys.where((k) => k != 'kind' && !data.contains(k)),
          ])
            BindingParameter(
              key,
              _parameterType(
                chart.types,
                SchemaTypes.map(props[key]),
                '${SchemaTypes.identifier(kind)}${SchemaTypes.identifier(key)}',
                nullable: !required.contains(key),
              ),
              keywordOnly: !data.contains(key),
              defaultValue: required.contains(key) ? null : 'None',
            ),
        ],
        chart.types.type(schema, '${SchemaTypes.identifier(kind)}Spec'),
        'Build a $kind chart spec.',
      ),
    );
  }
  graphics.constructor('Chart', chartSchema, graphicsSignature);

  // Compatibility constructors lower to the registered graphics catalog.
  // Their data layout differs from chart.*: ids are assigned during lowering.
  final bar = kinds.firstWhere(
    (s) =>
        SchemaTypes.map(SchemaTypes.map(s['properties'])['kind'])['const'] ==
        'bar',
  );
  final point = SchemaTypes.map(
    SchemaTypes.map(SchemaTypes.map(bar['properties'])['points'])['items'],
  );
  final barProps = SchemaTypes.map(point['properties'])..remove('id');
  final bars = {
    'type': 'array',
    'items': {
      ...point,
      'properties': barProps,
      'required': ['label', 'value'],
    },
  };
  final compatibility = {
    'BarChart': {
      'bars': bars,
      'title': {'type': 'string'},
      'action': {r'$ref': r'common_types.json#/$defs/Action'},
      'weight': {'type': 'number'},
    },
    'LineChart': {
      'labels': {
        'type': 'array',
        'items': {'type': 'string'},
      },
      'series': {
        'type': 'array',
        'items': {
          'type': 'object',
          'properties': {
            'label': {'type': 'string'},
            'values': {
              'type': 'array',
              'items': {
                'type': ['number', 'null'],
              },
            },
          },
          'required': ['label', 'values'],
          'additionalProperties': false,
        },
      },
      'title': {'type': 'string'},
      'weight': {'type': 'number'},
    },
  };
  for (final MapEntry(:key, :value) in compatibility.entries) {
    ui.constructor(key, {
      'type': 'object',
      'properties': value,
      'required': key == 'BarChart' ? ['bars'] : ['labels', 'series'],
    }, uiChartSignatures[key]!);
  }
  return {
    for (final m in [ui, workbench, chart, graphics]) m.name: m,
  };
}

final Map<String, ModuleBindings> moduleBindings = generateBindings();

PythonType _parameterType(
  SchemaTypes types,
  Map<String, Object?> schema,
  String name, {
  required bool nullable,
}) {
  final type = types.type(schema, name);
  return nullable ? type | pyNone : type;
}
